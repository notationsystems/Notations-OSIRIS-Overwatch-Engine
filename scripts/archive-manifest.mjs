#!/usr/bin/env node
/**
 * Sea Dog Terminal — archive manifest generator (shipping order S-2).
 *
 * Walks the two archive roots and writes data-archive/MANIFEST.json:
 * every file's sha256, byte count, and DURABILITY CLASS. The suite's
 * archiveManifest test verifies the manifest against the tree (every
 * entry resolves to matching bytes; every file is indexed), so a stale
 * manifest fails CI rather than rotting silently.
 *
 * Run after any archival: node scripts/archive-manifest.mjs
 *
 * Durability classes — the label a pruner needs in a year:
 *   unreconstructable   The upstream revises in place and keeps no prior
 *                       version. A lost file is a knowledge state gone
 *                       permanently. (All Comtrade captures.)
 *   refetchable_at_risk Re-fetchable today from a source that could
 *                       plausibly disappear or change shape (a frozen S3
 *                       export, a single republisher's page).
 *   refetchable         The upstream retains editions; loss costs a
 *                       re-fetch, not a vintage. (MCS, CFTC, Yahoo.)
 *   documentation       Human-written; reconstructable from the repo's
 *                       own history.
 */

import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

export const ARCHIVE_ROOTS = ['data-archive', 'src/data/economy/snapshots'];
export const MANIFEST_PATH = 'data-archive/MANIFEST.json';

/**
 * LIVE demand logs (final order, F-4 finding): the running instrument
 * appends search-misses.jsonl, export-log.jsonl, mcp-sessions.jsonl and
 * load-operations.jsonl into data-archive/ — so on any machine where the
 * instrument has been USED, an unruled path would fail buildManifest and a
 * growing file can never hash-match a static manifest. They are excluded from the
 * manifest contract BY NAME (an accounted-for drop, not a silent one):
 * append-only demand evidence, unreconstructable in kind, protected by
 * the mirror refresh rather than by a hash that would be stale the next
 * time someone uses the instrument.
 */
export const LIVE_LOGS = [
  'data-archive/search-misses.jsonl',
  'data-archive/export-log.jsonl',
  'data-archive/mcp-sessions.jsonl',
  'data-archive/load-operations.jsonl',
];

/** First matching rule wins. Paths are repo-relative with forward slashes. */
export const DURABILITY_RULES = [
  { prefix: 'data-archive/comtrade/', cls: 'unreconstructable' },
  { prefix: 'src/data/economy/snapshots/comtrade-', cls: 'unreconstructable' },
  { prefix: 'data-archive/openownership/', cls: 'refetchable_at_risk' },
  { prefix: 'src/data/economy/snapshots/westmetall-', cls: 'refetchable_at_risk' },
  { prefix: 'src/data/economy/snapshots/', cls: 'refetchable' },
  { prefix: 'data-archive/README.md', cls: 'documentation' },
];

export function durabilityClassOf(relPath) {
  const p = relPath.split(sep).join('/');
  const rule = DURABILITY_RULES.find(r => p.startsWith(r.prefix));
  return rule ? rule.cls : null;
}

export function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

export function buildManifest(cwd = process.cwd()) {
  const files = [];
  for (const root of ARCHIVE_ROOTS) {
    for (const full of walk(join(cwd, root))) {
      const rel = relative(cwd, full).split(sep).join('/');
      if (rel === MANIFEST_PATH) continue;
      if (LIVE_LOGS.includes(rel)) continue; // named exclusion — see LIVE_LOGS
      const bytes = readFileSync(full);
      const cls = durabilityClassOf(rel);
      if (!cls) throw new Error(`No durability rule covers ${rel} — add one; an unclassified archive file is an unlabelled risk.`);
      files.push({
        path: rel,
        sha256: createHash('sha256').update(bytes).digest('hex'),
        bytes: bytes.length,
        class: cls,
      });
    }
  }
  files.sort((a, b) => a.path.localeCompare(b.path));
  const counts = {};
  for (const f of files) counts[f.class] = (counts[f.class] ?? 0) + 1;
  return { note: 'Generated by scripts/archive-manifest.mjs — verified against the tree by the suite. Regenerate after any archival.', counts, files };
}

// Generate when run directly (not when imported by the verifier test).
if (process.argv[1] && process.argv[1].endsWith('archive-manifest.mjs')) {
  const manifest = buildManifest();
  writeFileSync(MANIFEST_PATH, JSON.stringify(manifest, null, 2) + '\n');
  console.log(`MANIFEST.json: ${manifest.files.length} files — ${Object.entries(manifest.counts).map(([k, v]) => `${k}=${v}`).join(', ')}`);
}
